// Metro can't parse a raw .sql file as a JS module (it tries to run it
// through the JS transformer and fails with a syntax error), which is what
// drizzle-kit's own generated `migrations.js` does by default
// (`import m0000 from './0000_xxx.sql'`). This script inlines each
// migration's SQL as a JS string instead, so nothing ever needs Metro to
// import a .sql file.
//
// Run automatically after `drizzle-kit generate` (see package.json's
// "db:generate" script) — never edit db/migrations/migrations.js by hand.

const fs = require('fs');
const path = require('path');

const migrationsDir = path.join(__dirname, '..', 'db', 'migrations');
const journalPath = path.join(migrationsDir, 'meta', '_journal.json');

const journal = JSON.parse(fs.readFileSync(journalPath, 'utf-8'));

const migrationKeys = [];
const migrationEntries = journal.entries.map((entry) => {
  const key = `m${String(entry.idx).padStart(4, '0')}`;
  const sqlPath = path.join(migrationsDir, `${entry.tag}.sql`);
  const sql = fs.readFileSync(sqlPath, 'utf-8');
  migrationKeys.push(key);
  return `  ${key}: ${JSON.stringify(sql)},`;
});

const output = `// AUTO-GENERATED by scripts/build-migrations.js — do not edit by hand.
// Regenerate with \`npm run db:generate\`.

const journal = ${JSON.stringify(journal, null, 2)};

const migrations = {
${migrationEntries.join('\n')}
};

module.exports = { journal, migrations };
`;

fs.writeFileSync(path.join(migrationsDir, 'migrations.js'), output);

console.log(`Wrote db/migrations/migrations.js with ${migrationKeys.length} migration(s).`);
